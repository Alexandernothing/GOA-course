// do while

let arr = [1, 2, 3, 4, 5]
let i = 0

do {
    console.log(arr[i])
    i++
} while(i < arr.length)

console.log("-----------------------------")

// while

let list = [1, 2, 3, 4, 5]

let ii = 0

while (ii < list.length) {
    console.log(list[ii])
    ii++
}